import { useEffect, useState } from "react";
import { Link, useParams } from "react-router-dom";
import { consumerApi } from "../../api/endpoints";
import { PageLoader, Banner } from "../../components/ui/Primitives";
import { formatDate } from "../../utils/date";

export default function Certificate() {
  const { id } = useParams();
  const [request, setRequest] = useState(null);

  useEffect(() => {
    consumerApi.getRequest(id).then((res) => setRequest(res.data));
  }, [id]);

  if (!request) return <PageLoader />;

  if (request.status !== "COMPLETED") {
    return (
      <div className="mx-auto max-w-lg">
        <Banner kind="info">A certificate is only available once a request has been completed.</Banner>
        <Link to={`/consumer/requests/${id}`} className="btn-secondary mt-4 inline-flex">Back to request</Link>
      </div>
    );
  }

  const totalWeight = request.items.reduce((sum, i) => sum + (i.actual_weight_kg || i.estimated_weight_kg) * i.quantity, 0);
  const completedEntry = [...request.history].reverse().find((h) => h.status === "COMPLETED");
  const completedDate = completedEntry ? completedEntry.created_at : request.updated_at;

  return (
    <div className="mx-auto max-w-2xl">
      <div className="mb-4 flex items-center justify-between print:hidden">
        <Link to={`/consumer/requests/${id}`} className="text-sm text-inkfaint hover:text-ink">← Back to request</Link>
        <button onClick={() => window.print()} className="btn-primary">Print / Save as PDF</button>
      </div>

      <div className="ticket relative border-2 p-8">
        <div className="absolute right-8 top-8 stamp animate-stamp border-circuit text-circuit" style={{ borderStyle: "double" }}>
          Recycled ✓
        </div>

        <div className="flex items-center gap-2">
          <div className="flex h-9 w-9 items-center justify-center rounded bg-ink text-circuit">
            <svg width="20" height="20" viewBox="0 0 32 32">
              <path d="M16 6 L24 11 V21 L16 26 L8 21 V11 Z" fill="none" stroke="currentColor" strokeWidth="1.8" />
              <circle cx="16" cy="16" r="3" fill="currentColor" />
            </svg>
          </div>
          <span className="text-lg font-semibold text-ink">Reloop</span>
        </div>

        <h1 className="mt-8 text-2xl font-semibold text-ink">Certificate of Responsible Recycling</h1>
        <p className="mt-2 text-sm text-inkfaint">
          This certifies that the e-waste items listed below were collected and processed through
          Reloop's verified pickup and segregation network.
        </p>

        <div className="ticket-divider my-6" />

        <div className="grid grid-cols-2 gap-4 text-sm">
          <div>
            <p className="field-label">Certificate for</p>
            <p className="mt-1 text-ink">{request.consumer_name}</p>
          </div>
          <div>
            <p className="field-label">Manifest ID</p>
            <p className="mt-1 font-mono text-ink">#{String(request.id).padStart(5, "0")}</p>
          </div>
          <div>
            <p className="field-label">Processed by</p>
            <p className="mt-1 text-ink">{request.centre_name}</p>
          </div>
          <div>
            <p className="field-label">Completion date</p>
            <p className="mt-1 text-ink">{formatDate(completedDate)}</p>
          </div>
        </div>

        <div className="ticket-divider my-6" />

        <p className="field-label">Items recycled</p>
        <div className="mt-3 space-y-2">
          {request.items.map((i) => (
            <div key={i.id} className="flex justify-between text-sm">
              <span className="text-ink">{i.category_name} × {i.quantity}</span>
              <span className="font-mono text-inkfaint">{(i.actual_weight_kg || i.estimated_weight_kg)} kg</span>
            </div>
          ))}
        </div>

        <div className="ticket-divider my-6" />

        <div className="flex items-center justify-between">
          <span className="field-label">Total weight diverted from landfill</span>
          <span className="font-mono text-xl font-semibold text-circuit">{totalWeight.toFixed(2)} kg</span>
        </div>

        <p className="mt-8 field-label">
          Generated by Reloop — a college demonstration project. This certificate is illustrative and
          not a substitute for formal EPR/CPCB compliance documentation.
        </p>
      </div>
    </div>
  );
}
